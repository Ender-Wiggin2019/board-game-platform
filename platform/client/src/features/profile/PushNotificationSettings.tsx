type TPushUiFailure =
  | TPushEnableFailure
  | 'server-config-invalid'
  | 'unexpected-enable-error';

type TPushMutationResult = {
  result: Awaited<ReturnType<typeof enablePushNotifications>> | undefined;
  session: ReturnType<typeof useAuthStore.getState>;
};

class PushEnableMutationError extends Error {
  public constructor(public readonly reason: TPushUiFailure) {
    super(reason);
    this.name = 'PushEnableMutationError';
  }
}

