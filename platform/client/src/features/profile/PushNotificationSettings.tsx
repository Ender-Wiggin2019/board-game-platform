/**
 * Turn-alert push notifications.
 *
 * The iOS path is the reason this is not just a switch. Safari exposes push only
 * to a web app launched from the Home Screen, so for a user in a normal tab the
 * honest UI is instructions, not a control that cannot work.
 */
export function PushNotificationSettings(): React.JSX.Element {
  const { t } = useTranslation('platform-common');
  const queryClient = useQueryClient();
  const [busy, setBusy] = useState(false);
  const [testResult, setTestResult] = useState<string | null>(null);
  const [onlineOnly, setOnlineOnly] = useState(false);
  const [onlineOnlyReason, setOnlineOnlyReason] = useState<
    TPushEnableFailure | undefined
  >();

  const { data: currentUser } = useCurrentUser();

  const config = useQuery({
    queryKey: ['push', 'config'],
    queryFn: () => pushApi.getConfig(),
    retry: shouldRetryHttpQuery,
    staleTime: 30_000,
  });

  // The stored preference is the switch's state, not the device count: it is the
  // record of intent that survives a subscription iOS has quietly invalidated,
  // and it is what stops the launch-time refresh re-subscribing someone who
  // turned this off. Absent means off, so new accounts start disabled.
  const enabled = currentUser?.preferences?.pushNotificationsEnabled === true;

  const toggle = useMutation({
    mutationFn: async (next: boolean): Promise<TPushMutationResult> => {
      const session = useAuthStore.getState();
      if (next) {
        const publicKey = config.data?.publicKey;
        const result = await enablePushNotifications(publicKey);
        if (!result.ok) throw new PushEnableMutationError(result.reason);
        return { result, session };
      } else {
        await disablePushNotifications();
        return { result: undefined, session };
      }
    },
    onMutate: (next) => {
      if (!next) {
        setOnlineOnly(false);
        setOnlineOnlyReason(undefined);
      }
    },
    onSuccess: (outcome, next) => {
      if (!isSameAuthSession(outcome.session)) return;
      const result = outcome.result;
      if (next && result?.ok && result.mode === 'online-only') {
        setOnlineOnly(true);
        setOnlineOnlyReason(result.reason);
      } else if (!next) {
        setOnlineOnly(false);
        setOnlineOnlyReason(undefined);
      }

      // The server has committed the account preference. Reflect that durable
      // state immediately while auth/me is revalidated below.
      queryClient.setQueryData<IAuthUser>(['auth', 'me'], (user) =>
        user
          ? {
              ...user,
              preferences: {
                ...user.preferences,
                pushNotificationsEnabled: next,
              },
            }
          : user,
      );
    },
    onError: () => {
      setOnlineOnly(false);
      setOnlineOnlyReason(undefined);
    },
    onSettled: () => {
      void queryClient.invalidateQueries({ queryKey: ['auth', 'me'] });
      void queryClient.invalidateQueries({ queryKey: ['push', 'config'] });
    },
  });

  const runTest = async (): Promise<void> => {
    setBusy(true);
    setTestResult(null);
    try {
      const delivered = await pushApi.sendTest();
      setTestResult(
        delivered > 0
          ? t('client.profile.push.test_sent', {
              count: delivered,
              defaultValue: 'Sent to {{count}} device(s).',
            })
          : t('client.profile.push.test_none', {
              defaultValue: 'No registered devices received it.',
            }),
      );
    } catch {
      setTestResult(
        t('client.profile.push.test_failed', { defaultValue: 'Test failed.' }),
      );
    } finally {
      setBusy(false);
    }
  };

  const availability = config.data
    ? getPushAvailability(
        config.data.configured && Boolean(config.data.publicKey),
      )
    : undefined;
  const toggleFailure: TPushUiFailure | undefined = toggle.isError
    ? toggle.error instanceof PushEnableMutationError
      ? toggle.error.reason
      : 'unexpected-enable-error'
    : undefined;
  const failure = availability?.blocker ?? toggleFailure;
  const failureCopy = failure ? PUSH_FAILURE_COPY[failure] : undefined;
  const onlineOnlyFailureCopy = onlineOnlyReason
    ? PUSH_FAILURE_COPY[onlineOnlyReason]
    : undefined;
  const reason = config.isPending
    ? t('client.profile.push.loading', {
        defaultValue: 'Loading push settings…',
      })
    : config.isError
      ? t('client.profile.push.config_failed', {
          defaultValue: 'Could not load push settings.',
        })
      : failureCopy
        ? t(failureCopy.key, { defaultValue: failureCopy.defaultValue })
        : onlineOnlyFailureCopy
          ? t(onlineOnlyFailureCopy.key, {
              defaultValue: onlineOnlyFailureCopy.defaultValue,
            })
          : null;
  const diagnosticCode = config.isError
    ? 'config-request-failed'
    : (failure ?? onlineOnlyReason);
  const showOnlineOnly =
    onlineOnly ||
    (enabled &&
      availability?.usable === true &&
      availability.webPushUsable === false);
  const cannotEnableOnThisDevice =
    !enabled &&
    (config.isPending || config.isError || availability?.usable !== true);

  return (
    <div className='flex min-w-0 flex-col items-start gap-1.5'>
      <div className='flex min-w-0 flex-wrap items-center gap-3'>
        <Switch
          id='profile-push-notifications'
          checked={enabled}
          disabled={toggle.isPending || cannotEnableOnThisDevice}
          onCheckedChange={(checked) => toggle.mutate(checked)}
          aria-label={t('client.profile.push.label', {
            defaultValue: 'Turn notifications',
          })}
        />
        {enabled ? (
          <Button
            type='button'
            variant='ghost'
            disabled={busy}
            onClick={runTest}
          >
            {t('client.profile.push.test', { defaultValue: 'Test' })}
          </Button>
        ) : null}
      </div>
      {reason ? (
        <div
          className='flex min-w-0 flex-wrap items-center gap-2 text-xs text-text-400'
          data-testid='push-notification-reason'
          aria-live='polite'
        >
          <span>{reason}</span>
          {diagnosticCode ? (
            <span>
              {t('client.profile.push.diagnostic_code', {
                code: diagnosticCode,
                defaultValue: 'Diagnostic code: {{code}}',
              })}
            </span>
          ) : null}
          {config.isError ? (
            <Button
              type='button'
              variant='ghost'
              onClick={() => void config.refetch()}
            >
              {t('client.profile.push.retry', { defaultValue: 'Retry' })}
            </Button>
          ) : null}
        </div>
      ) : null}
      {enabled || showOnlineOnly ? (
        <div
          className='text-xs text-text-400'
          data-testid='push-online-only'
          aria-live='polite'
        >
          {showOnlineOnly
            ? t('client.profile.push.online_only', {
                defaultValue:
                  'Notifications work while this page stays online; push after closing the page is currently unavailable.',
              })
            : t('client.profile.push.online_hint', {
                defaultValue:
                  "Online pages receive notifications directly; alerts after closing the page depend on your browser's push service.",
              })}
        </div>
      ) : null}
      {testResult ? (
        <span className='text-xs text-text-400' aria-live='polite'>
          {testResult}
        </span>
      ) : null}
    </div>
  );
}
